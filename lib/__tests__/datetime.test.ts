import { describe, expect, it } from "vitest";
import { addMinutes, atJstTime, ceilToMinutes, diffMinutesExact, toJstIso } from "@/lib/datetime";

describe("JSTの日時計算", () => {
  it.each([
    ["2026-10-04T22:00:00Z", "2026-10-05T07:00:00+09:00"],
    ["2026-12-31T15:00:00Z", "2027-01-01T00:00:00+09:00"],
    ["2026-10-05T07:30:00+09:00", "2026-10-05T07:30:00+09:00"],
  ])("toJstIso(%s)", (input, expected) => {
    expect(toJstIso(input)).toBe(expected);
  });

  it.each([
    ["2026-10-05", "09:00", "2026-10-05T09:00:00+09:00"],
    ["2026-12-31", "24:00", "2027-01-01T00:00:00+09:00"],
    ["2028-02-28", "24:00", "2028-02-29T00:00:00+09:00"],
    ["2028-02-29", "24:00", "2028-03-01T00:00:00+09:00"],
  ])("atJstTime(%s, %s)", (date, time, expected) => {
    expect(atJstTime(date, time)).toBe(expected);
  });

  it.each([
    ["2026-10-05T09:00:00+09:00", -50, "2026-10-05T08:10:00+09:00"],
    ["2026-10-05T13:00:00+09:00", 50, "2026-10-05T13:50:00+09:00"],
    ["2026-10-05T09:00:00+09:00", -12, "2026-10-05T08:48:00+09:00"],
    ["2026-12-31T23:59:00+09:00", 3, "2027-01-01T00:02:00+09:00"],
    ["2027-01-01T00:02:00+09:00", -3, "2026-12-31T23:59:00+09:00"],
  ])("addMinutes(%s, %s)", (input, minutes, expected) => {
    expect(addMinutes(input, minutes)).toBe(expected);
  });
});

// nowの切り上げには秒・ミリ秒も含める（planning.md 10.3・10.5）。
describe("空き時間用の日時計算", () => {
  it.each([
    ["2026-10-05T14:12:00+09:00", "2026-10-05T14:15:00+09:00"],
    ["2026-10-05T14:15:00+09:00", "2026-10-05T14:15:00+09:00"],
    ["2026-10-05T14:15:00.001+09:00", "2026-10-05T14:20:00+09:00"],
    ["2026-12-31T23:59:59+09:00", "2027-01-01T00:00:00+09:00"],
    ["2028-02-28T23:58:00+09:00", "2028-02-29T00:00:00+09:00"],
    ["2026-10-05T05:12:00Z", "2026-10-05T14:15:00+09:00"],
  ])("ceilToMinutes(%s, 5)", (input, expected) => {
    expect(ceilToMinutes(input, 5)).toBe(expected);
  });

  it("14分59秒を15分に丸めない", () => {
    expect(diffMinutesExact("2026-10-05T07:30:00+09:00", "2026-10-05T07:44:59+09:00")).toBeCloseTo(
      14 + 59 / 60,
    );
  });

  it.each([0, -5, 0.5])("不正な切り上げ単位%sを拒否する", (step) => {
    expect(() => ceilToMinutes("2026-10-05T14:12:00+09:00", step)).toThrow(RangeError);
  });
});
